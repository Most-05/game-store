// ตัวช่วยทำให้การ์ดสินค้าของร้าน ARK กดด้วยคีย์บอร์ดได้
//
// การ์ดสินค้าทุกใบในร้าน ARK เป็น <div onClick> ธรรมดา ซึ่งเบราว์เซอร์
// ไม่ถือว่าเป็นปุ่ม ผลคือกดด้วยเมาส์ได้อย่างเดียว ไล่ด้วยปุ่ม Tab ไปไม่ถึง
// กด Enter ไม่ติด และโปรแกรมอ่านหน้าจอก็ไม่ประกาศว่าของชิ้นนี้กดได้
// ซึ่งแปลว่าคนที่ใช้คีย์บอร์ดอย่างเดียวซื้อของในร้าน ARK ไม่ได้เลย
//
// ทางแก้ที่ถูกที่สุดคือเปลี่ยน div เป็น <button> แต่การ์ดพวกนี้มีรูปกับหัวเรื่อง
// อยู่ข้างใน การยัดทั้งก้อนเข้าไปใน button จะทำให้โครงเอกสารแปลก
// จึงใช้วิธีบอกเบราว์เซอร์ว่า div ก้อนนี้ทำหน้าที่เป็นปุ่ม แล้วรับปุ่มคีย์บอร์ดเอง
//
// รวมไว้ที่เดียวเพราะการ์ดกระจายอยู่หกหน้า ถ้าเขียนซ้ำทุกหน้าจะหลุดกันได้ง่าย
export function cardButtonProps(onActivate) {
  return {
    role: 'button',
    tabIndex: 0,
    onClick: onActivate,
    onKeyDown: (event) => {
      // Enter กับ Space คือสองปุ่มที่ <button> จริงตอบสนอง ต้องทำให้เหมือนกัน
      if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault(); // กันไม่ให้ Space เลื่อนหน้าลงไปด้วย
        onActivate();
      }
    },
  };
}
